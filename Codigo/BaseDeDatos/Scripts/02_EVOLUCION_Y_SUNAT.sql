SELECT 
    c.id_compra, 
    c.serie_comprobante, 
    c.numero_comprobante, 
    c.fecha_emision,
    tc.nombre AS nombre_tipo_comprobante,
    p.numero_documento AS numero_documento_proveedor, 
    p.razon_social AS razon_social_proveedor,
    c.subtotal, 
    c.impuesto AS igv, 
    c.total, 
